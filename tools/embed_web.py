"""PlatformIO pre-build step: docs/index.html -> include/web_index.h (gzip, PROGMEM).

The same docs/index.html is published by GitHub Pages (Bluetooth mode over HTTPS) and served by
the board itself at http://<board>/ (Wi-Fi mode), so the two never drift apart.
"""
import gzip
import os

Import("env")  # noqa: F821  (provided by PlatformIO / SCons)

root = env.subst("$PROJECT_DIR")  # noqa: F821
source = os.path.join(root, "docs", "index.html")
target = os.path.join(root, "include", "web_index.h")

with open(source, "rb") as f:
    data = gzip.compress(f.read(), compresslevel=9, mtime=0)

lines = ["// Generated by tools/embed_web.py from docs/index.html - do not edit.",
         "#pragma once", "#include <Arduino.h>", "",
         f"constexpr std::size_t kWebIndexGzSize = {len(data)};",
         "const std::uint8_t kWebIndexGz[] PROGMEM = {"]
for i in range(0, len(data), 20):
    lines.append("    " + ", ".join(f"0x{b:02X}" for b in data[i:i + 20]) + ",")
lines.append("};")
text = "\n".join(lines) + "\n"

old = open(target, encoding="utf-8").read() if os.path.exists(target) else ""
if old != text:
    with open(target, "w", encoding="utf-8", newline="\n") as f:
        f.write(text)
print(f"embed_web: {os.path.relpath(source, root)} -> {len(data)} bytes gzip")
