"""Builds the anti-aliased Chinese fonts used by src/ui.cpp.

TFT_eSPI smooth fonts use the Processing .vlw layout. This script renders only the glyphs the
UI needs (printable ASCII + every non-ASCII character found in the source files) with Microsoft
YaHei and writes them as PROGMEM arrays:

    include/font_zh16.h   kFontZh16   16 px
    include/font_zh24.h   kFontZh24   24 px

Re-run after adding or changing Chinese text:  python tools/make_fonts.py
"""
import os
import struct
import sys

from PIL import Image, ImageDraw, ImageFont

ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
SOURCES = [os.path.join(ROOT, 'src', 'ui.cpp')]
FONT_FILE = r'C:\Windows\Fonts\msyh.ttc'
SIZES = [(16, 'font_zh16.h', 'kFontZh16'), (24, 'font_zh24.h', 'kFontZh24')]
EXTRA = '°Ω…'


def collect_chars():
    chars = {chr(c) for c in range(0x20, 0x7F)}
    for path in SOURCES:
        with open(path, encoding='utf-8') as f:
            for ch in f.read():
                if ord(ch) > 0x7E and ch not in '\r\n\t':
                    chars.add(ch)
    chars.update(EXTRA)
    return sorted(chars, key=ord)


def build_vlw(chars, size):
    font = ImageFont.truetype(FONT_FILE, size)
    ascent, descent = font.getmetrics()
    metrics = []
    bitmaps = []
    for ch in chars:
        advance = int(round(font.getlength(ch)))
        x0, y0, x1, y1 = font.getbbox(ch, anchor='ls')     # relative to the baseline origin
        width, height = max(0, x1 - x0), max(0, y1 - y0)
        if ch == ' ' or width == 0 or height == 0:
            width = height = 0
            data = b''
            x0 = 0
            y0 = 0
        else:
            image = Image.new('L', (width, height), 0)
            ImageDraw.Draw(image).text((-x0, -y0), ch, font=font, fill=255, anchor='ls')
            data = image.tobytes()
        if width > 255 or height > 255:
            raise SystemExit(f'glyph too large: {ch!r}')
        # unicode, height, width, xAdvance, dY (top above baseline), dX, padding
        metrics.append(struct.pack('>7i', ord(ch), height, width, advance, -y0, x0, 0))
        bitmaps.append(data)
    header = struct.pack('>6i', len(chars), 11, size, 0, ascent, descent)
    return header + b''.join(metrics) + b''.join(bitmaps)


def write_header(path, name, blob, size, count):
    lines = [
        '#pragma once',
        '',
        f'// Generated by tools/make_fonts.py: Microsoft YaHei {size} px, {count} glyphs, {len(blob)} bytes.',
        '// TFT_eSPI smooth font (vlw layout). Do not edit by hand.',
        '',
        '#include <pgmspace.h>',
        '#include <cstdint>',
        '',
        f'const std::uint8_t {name}[] PROGMEM = {{',
    ]
    for i in range(0, len(blob), 24):
        lines.append('    ' + ', '.join(f'0x{b:02x}' for b in blob[i:i + 24]) + ',')
    lines.append('};')
    with open(path, 'w', encoding='utf-8', newline='\n') as f:
        f.write('\n'.join(lines) + '\n')


def main():
    chars = collect_chars()
    cjk = [c for c in chars if ord(c) > 0x7E]
    print(f'{len(chars)} glyphs ({len(cjk)} non-ASCII)')
    for size, filename, name in SIZES:
        blob = build_vlw(chars, size)
        write_header(os.path.join(ROOT, 'include', filename), name, blob, size, len(chars))
        print(f'{filename}: {len(blob)} bytes')


if __name__ == '__main__':
    sys.exit(main())
