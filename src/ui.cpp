bool pushTextLine(std::uint32_t start) {
    if (textLineCount == textCapacity) {
        const int capacity = textCapacity > 0 ? textCapacity * 2 : 4096;
        void* p = heap_caps_realloc(textStarts, static_cast<std::size_t>(capacity) * sizeof(std::uint32_t),
            MALLOC_CAP_SPIRAM | MALLOC_CAP_8BIT);
        if (p == nullptr) {
            return false;
        }
        textStarts = static_cast<std::uint32_t*>(p);
        textCapacity = capacity;
    }
    textStarts[textLineCount++] = start;
    return true;
}

bool latinWordChar(std::uint32_t c) {
    return (c >= '0' && c <= '9') || (c >= 'A' && c <= 'Z') || (c >= 'a' && c <= 'z') || c == '\'' || c == '-' || c == '_'
        || (c >= 0xC0 && c <= 0x24F);
}

bool noLineStart(std::uint32_t c) {     // closing punctuation that should not begin a line
    switch (c) {
        case ',': case '.': case ';': case ':': case '!': case '?': case ')': case ']':
        case 0x3001: case 0x3002: case 0xFF0C: case 0xFF0E: case 0xFF1B: case 0xFF1A: case 0xFF01: case 0xFF1F:
        case 0xFF09: case 0x3011: case 0x300B: case 0x300D: case 0x300F: case 0x201D: case 0x2019: case 0x2026:
            return true;
        default:
            return false;
    }
}

// Word-wraps the whole text once (about 0.5 s per MB); lines are kept as byte offsets. Latin words
// move to the next line whole; CJK text breaks anywhere except before closing punctuation.
void layoutText(const char* data, std::size_t size) {
    loadReaderSize();
    const textfont::Style style = readerStyle();
    textBase = data;
    textBytes = size;
    textLineCount = 0;
    textTop = 0;
    const char* p = data;
    const char* end = data + size;
    if (size >= 3 && static_cast<std::uint8_t>(p[0]) == 0xEF && static_cast<std::uint8_t>(p[1]) == 0xBB
        && static_cast<std::uint8_t>(p[2]) == 0xBF) {
        p += 3;                          // UTF-8 BOM
    }
    std::uint32_t lineStart = static_cast<std::uint32_t>(p - data);
    std::uint32_t breakAt = lineStart;  // after the last space / non-Latin character on this line
    int width = 0;
    int widthAtBreak = 0;
    while (p < end) {
        const char* at = p;
        const std::uint32_t code = textfont::decode(p, end);
        if (code == '\n') {
            if (!pushTextLine(lineStart)) {
                return;
            }
            lineStart = breakAt = static_cast<std::uint32_t>(p - data);
            width = widthAtBreak = 0;
            continue;
        }
        if (code == '\r') {
            continue;
        }
        const int adv = textfont::advance(code == '\t' ? ' ' : code, style);
        if (width > 0 && width + adv > kTextW && !(noLineStart(code) && width + adv <= kTextHang)) {
            if (!pushTextLine(lineStart)) {
                return;
            }
            if (latinWordChar(code) && breakAt > lineStart) {
                lineStart = breakAt;            // the word in progress moves down whole
                width -= widthAtBreak;
            } else {
                lineStart = static_cast<std::uint32_t>(at - data);
                width = 0;
            }
            breakAt = lineStart;
            widthAtBreak = 0;
        }
        width += adv;
        if (!latinWordChar(code)) {
            breakAt = static_cast<std::uint32_t>(p - data);
            widthAtBreak = width;
        }
    }
    if (lineStart < size || textLineCount == 0) {
        pushTextLine(lineStart);
    }
}

void drawTextLine(int index, int y) {
    if (index < 0 || index >= textLineCount || textBase == nullptr) {
        return;
    }
    const std::uint32_t from = textStarts[index];
    const std::uint32_t to = index + 1 < textLineCount ? textStarts[index + 1] : static_cast<std::uint32_t>(textBytes);
    char buffer[512];
    std::size_t n = 0;
    for (std::uint32_t i = from; i < to && n + 1 < sizeof(buffer); ++i) {
        const char c = textBase[i];
        if (c != '\n' && c != '\r') {
            buffer[n++] = c;
        }
    }
    buffer[n] = '\0';
    drawUtf8(kTextX, y, kTextHang, buffer, kFg, kBg, readerStyle());
}

// A− / A+: re-wrap at the new size and stay at the same place in the text.
void setReaderSize(int size) {
    size = std::max(0, std::min(kReaderSizeCount - 1, size));
    if (size == readerSize || textBase == nullptr) {
        return;
    }
    const std::uint32_t anchor = textLineCount > 0 ? textStarts[std::min(textTop, textLineCount - 1)] : 0;
    readerSize = size;
    Preferences prefs;
    prefs.begin("share", false);
    prefs.putUChar("tsize", static_cast<std::uint8_t>(size));
    prefs.end();
    layoutText(textBase, textBytes);
    int top = 0;
    while (top + 1 < textLineCount && textStarts[top + 1] <= anchor) {
        ++top;
    }
    textTop = top;
}

void openShared(std::uint16_t id) {
    share::Item it;
    shareNote = "";
    if (!share::find(id, it)) {
        shareView = ShareView::List;
        return;
    }
    shareId = id;
    shareSel = share::indexOf(id);
    if (it.kind == share::Kind::Image) {
        shareView = ShareView::Image;
        zoomLevel = 0;
        viewCx = viewCy = 0.5f;
        toolbarUntil = millis() + 3000;       // show the controls for a moment
        return;
    }
    const std::uint8_t* data = nullptr;
    std::size_t size = 0;
    if (share::load(id, data, size)) {
        layoutText(reinterpret_cast<const char*>(data), size);
        shareView = ShareView::Text;
    } else {
        shareView = ShareView::List;
        shareNote = tr("读取失败", "Cannot read the file");
    }
}

