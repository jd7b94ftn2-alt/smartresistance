int wrap(int value, int count) {
    return ((value % count) + count) % count;
}

std::uint32_t stepClamped(std::uint32_t value, int steps, std::uint32_t stepSize, std::uint32_t low,
    std::uint32_t high) {
    const std::int64_t next = static_cast<std::int64_t>(value) + static_cast<std::int64_t>(steps) * stepSize;
    return static_cast<std::uint32_t>(std::min<std::int64_t>(high, std::max<std::int64_t>(low, next)));
}

