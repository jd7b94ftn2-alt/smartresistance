String bytesShort(std::uint32_t bytes) {
    if (bytes < 1024) {
        return String(bytes) + "B";
    }
    if (bytes < 1024UL * 1024UL) {
        return String((bytes + 512) / 1024) + "K";
    }
    return String(bytes / 1048576.0f, 2) + "M";
}

