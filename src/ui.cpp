void begin() {
    const esp_reset_reason_t reason = esp_reset_reason();
    bootCrumb = (reason == ESP_RST_TASK_WDT || reason == ESP_RST_PANIC || reason == ESP_RST_INT_WDT) ? diagCrumb : 0;
    diagCrumb = 0;
    pinMode(board::kEncoderA, INPUT_PULLUP);
    pinMode(board::kEncoderB, INPUT_PULLUP);
    pinMode(board::kEncoderSwitch, INPUT_PULLUP);
    pinMode(board::kTouchIrq, INPUT_PULLUP);
    encoderState = static_cast<std::uint8_t>(
        (digitalRead(board::kEncoderA) << 1) | digitalRead(board::kEncoderB));
    attachInterrupt(digitalPinToInterrupt(board::kEncoderA), onEncoderEdge, CHANGE);
    attachInterrupt(digitalPinToInterrupt(board::kEncoderB), onEncoderEdge, CHANGE);

    ledcSetup(kBacklightChannel, 5000, 8);
    ledcAttachPin(board::kTftBacklight, kBacklightChannel);
    ledcWrite(kBacklightChannel, 0);

    tft.init();
    resetSlots();
    applyDisplaySettings();
    tft.fillScreen(kBg);

    canvas.setColorDepth(16);
    if (canvas.createSprite(kWidth, kHeight) != nullptr) {
        shadow = static_cast<std::uint16_t*>(ps_malloc(static_cast<std::size_t>(kWidth) * kHeight * 2));
        if (shadow != nullptr) {
            canvas.fillSprite(kBg);
            memcpy(shadow, canvas.getPointer(), static_cast<std::size_t>(kWidth) * kHeight * 2);
            gfx = &canvas;
        } else {
            canvas.deleteSprite();
        }
    }
}

void applyDisplaySettings() {
    const app::Settings& config = app::settings();
    tft.setRotation(config.rotation == 3 ? 3 : 1);
    ledcWrite(kBacklightChannel, static_cast<std::uint32_t>(config.backlight) * 255 / 100);
    resetSlots();
    invalidatePanel();       // the frame buffer is still valid, the panel needs all of it again
    dirty = true;
}

String screenshot(int firstRow, int rows) {
    if (gfx != &canvas) {
        return "ERR no frame buffer";
    }
    firstRow = std::max(0, std::min(kHeight - 1, firstRow));
    rows = std::max(1, std::min(kHeight - firstRow, rows));
    const std::uint8_t* frame = static_cast<const std::uint8_t*>(canvas.getPointer());
    static std::uint8_t rle[kWidth * 3];
    static unsigned char encoded[kWidth * 4 + 8];
    String out;
    out.reserve(32 + rows * 160);
    out = String("SHOT ") + kWidth + " " + kHeight + " " + firstRow + " " + rows;
    for (int y = firstRow; y < firstRow + rows; ++y) {
        const std::uint8_t* p = frame + static_cast<std::size_t>(y) * kWidth * 2;   // big-endian RGB565
        int used = 0;
        int x = 0;
        while (x < kWidth) {
            int run = 1;
            while (x + run < kWidth && run < 256 && p[(x + run) * 2] == p[x * 2] && p[(x + run) * 2 + 1] == p[x * 2 + 1]) {
                ++run;
            }
            rle[used++] = static_cast<std::uint8_t>(run - 1);
            rle[used++] = p[x * 2];
            rle[used++] = p[x * 2 + 1];
            x += run;
        }
        std::size_t length = 0;
        if (mbedtls_base64_encode(encoded, sizeof(encoded), &length, rle, used) != 0) {
            return "ERR encode";
        }
        out += '\n';
        out += y;
        out += ' ';
        out += reinterpret_cast<const char*>(encoded);
    }
    return out;
}

void setPage(Page page) {
    if (page >= Page::Count) {
        return;
    }
    if (page == Page::TouchCal) {
        startTouchCalibration();
        return;
    }
    requestedPage = page;
    pageChangePending = true;
}

Page page() {
    return currentPage;
}

void startTouchCalibration() {
    if (currentPage != Page::TouchCal) {
        returnPage = currentPage == Page::Menu ? Page::About : currentPage;
    }
    requestedPage = Page::TouchCal;
    pageChangePending = true;
}

