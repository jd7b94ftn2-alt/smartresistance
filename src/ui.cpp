// Least-squares affine fit: screen = a*rx + b*ry + c (one 3x3 solve per axis).
bool solve3(double m[3][3], const double rhs[3], double out[3]) {
    double a[3][4];
    for (int r = 0; r < 3; ++r) {
        for (int c = 0; c < 3; ++c) {
            a[r][c] = m[r][c];
        }
        a[r][3] = rhs[r];
    }
    for (int col = 0; col < 3; ++col) {
        int pivot = col;
        for (int r = col + 1; r < 3; ++r) {
            if (std::fabs(a[r][col]) > std::fabs(a[pivot][col])) {
                pivot = r;
            }
        }
        if (std::fabs(a[pivot][col]) < 1e-9) {
            return false;
        }
        for (int c = 0; c < 4; ++c) {
            std::swap(a[col][c], a[pivot][c]);
        }
        for (int r = 0; r < 3; ++r) {
            if (r == col) {
                continue;
            }
            const double factor = a[r][col] / a[col][col];
            for (int c = col; c < 4; ++c) {
                a[r][c] -= factor * a[col][c];
            }
        }
    }
    for (int r = 0; r < 3; ++r) {
        out[r] = a[r][3] / a[r][r];
    }
    return true;
}

bool finishCalibration() {
    double m[3][3] = {{0, 0, 0}, {0, 0, 0}, {0, 0, 0}};
    double bx[3] = {0, 0, 0};
    double by[3] = {0, 0, 0};
    for (int i = 0; i < 4; ++i) {
        const double v[3] = {calRawX[i], calRawY[i], 1.0};
        for (int r = 0; r < 3; ++r) {
            for (int c = 0; c < 3; ++c) {
                m[r][c] += v[r] * v[c];
            }
            bx[r] += v[r] * kCalX[i];
            by[r] += v[r] * kCalY[i];
        }
    }
    double mx[3][3];
    double my[3][3];
    for (int r = 0; r < 3; ++r) {
        for (int c = 0; c < 3; ++c) {
            mx[r][c] = m[r][c];
            my[r][c] = m[r][c];
        }
    }
    double cx[3];
    double cy[3];
    if (!solve3(mx, bx, cx) || !solve3(my, by, cy)) {
        return false;
    }
    for (int i = 0; i < 4; ++i) {
        const double ex = cx[0] * calRawX[i] + cx[1] * calRawY[i] + cx[2] - kCalX[i];
        const double ey = cy[0] * calRawX[i] + cy[1] * calRawY[i] + cy[2] - kCalY[i];
        if (std::fabs(ex) > 20 || std::fabs(ey) > 20) {
            return false;
        }
    }
    app::Settings& config = app::settings();
    for (int i = 0; i < 3; ++i) {
        config.touchCal[i] = static_cast<float>(cx[i]);
        config.touchCal[3 + i] = static_cast<float>(cy[i]);
    }
    config.touchRotation = config.rotation;
    config.touchValid = true;
    config.touchSkipped = false;
    app::saveSettings();
    return true;
}

void restartCalibration() {
    calStep = 0;
    calSamples = 0;
    calSumX = 0;
    calSumY = 0;
    calWaitRelease = false;
    calReleaseCount = 0;
    drawCalibrationTarget();
}

void serviceCalibration(std::uint32_t now) {
    if (now - lastTouchPollMs < kTouchPollMs) {
        return;
    }
    lastTouchPollMs = now;
    std::uint16_t rx = 0;
    std::uint16_t ry = 0;
    std::uint16_t rz = 0;
    const bool down = readTouchRaw(rx, ry, rz);
    if (calWaitRelease) {
        calReleaseCount = down ? 0 : calReleaseCount + 1;
        if (calReleaseCount >= 3) {
            calWaitRelease = false;
            if (calStep < 4) {
                drawCalibrationTarget();
            }
        }
        return;
    }
    if (!down) {
        calSamples = 0;
        calSumX = 0;
        calSumY = 0;
        return;
    }
    calSumX += rx;
    calSumY += ry;
    if (++calSamples < 6) {
        return;
    }
    calRawX[calStep] = static_cast<float>(calSumX) / calSamples;
    calRawY[calStep] = static_cast<float>(calSumY) / calSamples;
    calSamples = 0;
    calSumX = 0;
    calSumY = 0;
    calWaitRelease = true;
    calReleaseCount = 0;
    gfx->fillCircle(kCalX[calStep], kCalY[calStep], 7, kGood);
    if (++calStep < 4) {
        return;
    }
    gfx->fillRect(0, 0, kWidth, kHeight, kBg);   // not fillScreen: a sprite keeps the 240x320 default size there
    if (finishCalibration()) {
        text(tr("校准完成", "Calibration done"), kWidth / 2, kHeight / 2, Font::Large, kGood, kBg, 0, MC_DATUM, 2);
        delay(800);
        requestedPage = returnPage;
        pageChangePending = true;
    } else {
        text(tr("校准失败，请重新点击", "Failed, please try again"), kWidth / 2, kHeight / 2, Font::Large, kBad, kBg, 0,
            MC_DATUM, 2);
        delay(1000);
        restartCalibration();
    }
}

