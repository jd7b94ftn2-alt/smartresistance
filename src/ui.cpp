void begin() {
    pinMode(board::kEncoderA, INPUT_PULLUP);
    pinMode(board::kEncoderB, INPUT_PULLUP);
    pinMode(board::kEncoderSwitch, INPUT_PULLUP);
    pinMode(board::kTouchIrq, INPUT_PULLUP);
    encoderState = static_cast<std::uint8_t>(
        (digitalRead(board::kEncoderA) << 1) | digitalRead(board::kEncoderB));
    attachInterrupt(digitalPinToInterrupt(board::kEncoderA), onEncoderEdge, CHANGE);
    attachInterrupt(digitalPinToInterrupt(board::kEncoderB), onEncoderEdge, CHANGE);

    ledcSetup(kBacklightChannel, 5000, 8);
    ledcAttachPin(board::kTftBacklight, kBacklightChannel);
    ledcWrite(kBacklightChannel, 0);

    tft.init();
    resetSlots();
    applyDisplaySettings();
    tft.fillScreen(kBg);
}

void applyDisplaySettings() {
    const app::Settings& config = app::settings();
    tft.setRotation(config.rotation == 3 ? 3 : 1);
    ledcWrite(kBacklightChannel, static_cast<std::uint32_t>(config.backlight) * 255 / 100);
    resetSlots();
    dirty = true;
}

void setPage(Page page) {
    if (page >= Page::Count) {
        return;
    }
    if (page == Page::TouchCal) {
        startTouchCalibration();
        return;
    }
    requestedPage = page;
    pageChangePending = true;
}

Page page() {
    return currentPage;
}

void startTouchCalibration() {
    if (currentPage != Page::TouchCal) {
        returnPage = currentPage == Page::Menu ? Page::About : currentPage;
    }
    requestedPage = Page::TouchCal;
    pageChangePending = true;
}

bool touchRaw(std::uint16_t& x, std::uint16_t& y, std::uint16_t& z) {
    return readTouchRaw(x, y, z);
}

void loop() {
    if (pageChangePending) {
        pageChangePending = false;
        Page target = requestedPage;
        // First boot with a touch panel that was never calibrated: calibrate once, the knob skips.
        if (!bootChecked) {
            bootChecked = true;
            const app::Settings& config = app::settings();
            if (!config.touchValid && !config.touchSkipped && target != Page::TouchCal) {
                returnPage = target;
                target = Page::TouchCal;
            }
        }
        if (target != Page::Menu && target != Page::TouchCal) {
            returnPage = target;
        }
        enterPage(target);
    }

    const std::uint32_t now = millis();
    if (currentPage == Page::TouchCal) {
        serviceCalibration(now);
        if (pollButton() != Press::None) {
            onShortPress();
        }
        takeEncoderSteps();
        return;
    }

    pollTouch(now);

    const int steps = takeEncoderSteps();
    if (steps != 0) {
        onRotate(steps);
        dirty = true;
    }

    switch (pollButton()) {
        case Press::Short:
            onShortPress();
            dirty = true;
            break;
        case Press::Long:
            if (currentPage != Page::Menu) {
                goHome();
            }
            break;
        default:
            break;
    }

    if (dirty || now - lastRefreshMs >= kRefreshMs) {
        lastRefreshMs = now;
        dirty = false;
        renderPage();
    }
}

