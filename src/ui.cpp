void clearContent() {
    useFont(Font::Builtin);
    tft.fillScreen(kBg);
    resetSlots();
    if (currentPage == Page::TouchCal) {
        return;
    }
    tft.fillRect(0, 0, kWidth, kBar, kBarColor);
    tft.drawFastHLine(0, kBar, kWidth, kBorder);
    switch (currentPage) {
        case Page::Resistor: staticResistor(); break;
        case Page::Ntc: staticNtc(); break;
        default: break;
    }
}

void enterPage(Page page) {
    // Leaving a page: stop what only makes sense while it is shown.
    if (currentPage == Page::RelayTest && page != Page::RelayTest) {
        app::leaveRawMode();
    }
    if (currentPage == Page::Serial && page != Page::Serial) {
        comm::setBridgePaused(false);
    }
    if (currentPage != Page::Menu && page == Page::Menu) {
        app::saveSettings();
    }

    currentPage = page;
    knobArmed = false;
    bridgeDrawnRev = 0xFFFFFFFF;
    tempDrawnCount = -1;
    touchHeld = true;          // ignore the finger that is still on the glass after a page change
    touchRepeat = false;
    if (page == Page::Ntc) {
        ntcEditTemp = app::ntcTemperature();
    }
    if (page == Page::Messages) {
        msgScroll = 0;
        msg::markAllRead();
    }
    if (page == Page::Menu) {
        for (int i = 0; i < kHomeCount; ++i) {
            if (kHome[i].page == returnPage) {
                homeIndex = i;
            }
        }
    }
    clearContent();
    if (page == Page::TouchCal) {
        restartCalibration();
    }
    dirty = true;
}

void renderPage() {
    if (currentPage == Page::TouchCal) {
        return;
    }
    drawStatusBar();
    switch (currentPage) {
        case Page::Menu: renderHome(); break;
        case Page::Resistor: renderResistor(); break;
        case Page::Ntc: renderNtc(); break;
        case Page::Bluetooth: renderBluetooth(); break;
        case Page::Knob: renderKnob(); break;
        case Page::Serial: renderSerial(); break;
        case Page::TempLog: renderTempLog(); break;
        case Page::Info: renderInfo(); break;
        case Page::RelayTest: renderRelayTest(); break;
        case Page::About: renderAbout(); break;
        case Page::Messages: renderMessages(); break;
        default: break;
    }
}

enum class Tap : std::uint8_t { None, Done, Repeat };

Tap onTouch(int x, int y) {
    if (currentPage != Page::Menu && y < kBar && x < 80) {
        goHome();
        return Tap::Done;
    }
    // "新消息 N" in the status bar opens the message list.
    if (y < kBar && x >= 166 && x < 266 && msg::count() > 0 && currentPage != Page::Messages) {
        returnPage = currentPage;
        setPage(Page::Messages);
        return Tap::Done;
    }
    app::Settings& config = app::settings();
    switch (currentPage) {
        case Page::Info:
            if (y >= kInfoCardY && msg::count() > 0) {
                setPage(Page::Messages);
                return Tap::Done;
            }
            break;

        case Page::Messages:
            if (y >= kBar) {
                scrollMessages(y < kHeight / 2 ? -1 : 1);
                return Tap::Repeat;
            }
            break;

        case Page::Menu:
            for (int i = 0; i < kHomeCount; ++i) {
                if (homeTile(i).contains(x, y)) {
                    homeIndex = i;
                    setPage(kHome[i].page);
                    return Tap::Done;
                }
            }
            break;

        case Page::Resistor:
            for (int i = 0; i < 6; ++i) {
                const int dx = digitX(i);
                if (x >= dx - 4 && x < dx + 36 && y >= 28 && y < 108) {
                    resistorField = i;
                    if (!app::state().locked) {
                        app::adjustDigit(static_cast<std::uint8_t>(5 - i), y < 67 ? 1 : -1);
                    }
                    return Tap::Repeat;
                }
            }
            if (kOutputButton.contains(x, y)) {
                resistorField = 6;
                app::setOutput(!app::state().outputEnabled);
                return Tap::Done;
            }
            break;

        case Page::Ntc:
            if (kNtcType.contains(x, y)) {
                ntcField = 0;
                stepNtcType(x < kNtcType.x + kNtcType.w / 2 ? -1 : 1);
                return Tap::Done;
            }
            for (int i = 0; i < 4; ++i) {
                if (kNtcStep[i].contains(x, y)) {
                    ntcField = (i == 0 || i == 3) ? 1 : 2;
                    stepNtc(kNtcStepValue[i]);
                    return Tap::Repeat;
                }
            }
            if (kNtcOutput.contains(x, y)) {
                ntcField = 3;
                const bool on = !app::state().outputEnabled;
                if (on && !app::ntcActive()) {
                    app::setNtcTemperature(ntcEditTemp);
                }
                app::setOutput(on);
                return Tap::Done;
            }
            break;

        case Page::Bluetooth:
            for (int i = 0; i < 2; ++i) {
                if (kBleMode[i].contains(x, y)) {
                    bleField = 0;
                    setBleBridgeMode(i == 1);
                    return Tap::Done;
                }
            }
            if (kBleToggle.contains(x, y)) {
                bleField = 1;
                setBleOn(!comm::bleEnabled());
                return Tap::Done;
            }
            break;

        case Page::Knob:
            for (int i = 0; i < 4; ++i) {
                if (kKnobMode[i].contains(x, y)) {
                    config.knobMode = static_cast<std::uint8_t>(i);
                    knobArmed = false;
                    return Tap::Done;
                }
            }
            if (kKnobStart.contains(x, y)) {
                knobArmed = !knobArmed;
                return Tap::Done;
            }
            break;

        case Page::Serial:
            if (kSerialBaud.contains(x, y)) {
                int index = 0;
                for (int i = 0; i < kBaudCount; ++i) {
                    if (kBaudRates[i] == config.bridgeBaud) {
                        index = i;
                    }
                }
                config.bridgeBaud = kBaudRates[wrap(index + 1, kBaudCount)];
                comm::setBridgeBaud(config.bridgeBaud);
                return Tap::Done;
            }
            if (kSerialPause.contains(x, y)) {
                comm::setBridgePaused(!comm::bridgePaused());
                return Tap::Done;
            }
            if (kSerialClear.contains(x, y)) {
                comm::clearBridgeLog();
                return Tap::Done;
            }
            break;

        case Page::TempLog:
            if (kLogInterval.contains(x, y)) {
                int index = 0;
                for (int i = 0; i < kLogIntervalCount; ++i) {
                    if (kLogIntervals[i] == config.logIntervalS) {
                        index = i;
                    }
                }
                config.logIntervalS = kLogIntervals[wrap(index + 1, kLogIntervalCount)];
                return Tap::Done;
            }
            if (kLogClear.contains(x, y)) {
                app::clearTempLog();
                return Tap::Done;
            }
            break;

        case Page::RelayTest:
            for (int row = 0; row < 4; ++row) {
                if (relayMinus(row).contains(x, y) || relayPlus(row).contains(x, y)) {
                    relayField = row;
                    adjustRelayRow(row, relayPlus(row).contains(x, y) ? 1 : -1);
                    return Tap::Repeat;
                }
            }
            if (kRelayStart.contains(x, y)) {
                relayField = 4;
                toggleRelayCycle();
                return Tap::Done;
            }
            break;

        case Page::About:
            if (kLightMinus.contains(x, y) || kLightPlus.contains(x, y)) {
                settingsField = 0;
                setBacklightSteps(kLightPlus.contains(x, y) ? 1 : -1);
                return Tap::Repeat;
            }
            if (kFlipButton.contains(x, y)) {
                settingsField = 1;
                flipScreen();
                return Tap::Done;
            }
            if (kLangButton.contains(x, y)) {
                settingsField = 2;
                toggleLanguage();
                return Tap::Done;
            }
            if (kCalButton.contains(x, y)) {
                settingsField = 3;
                startTouchCalibration();
                return Tap::Done;
            }
            if (kTouchOffButton.contains(x, y) && config.touchValid) {
                config.touchValid = false;
                config.touchSkipped = true;
                app::saveSettings();
                return Tap::Done;
            }
            break;

        default:
            break;
    }
    return Tap::None;
}

void pollTouch(std::uint32_t now) {
    if (now - lastTouchPollMs < kTouchPollMs) {
        return;
    }
    lastTouchPollMs = now;
    if (!app::settings().touchValid) {
        return;
    }
    std::uint16_t rx = 0;
    std::uint16_t ry = 0;
    std::uint16_t rz = 0;
    if (!readTouchRaw(rx, ry, rz)) {
        touchDownCount = 0;
        touchHeld = false;
        return;
    }
    if (++touchDownCount < 2) {
        return;   // two consecutive samples before a tap counts
    }
    int x = 0;
    int y = 0;
    mapTouch(rx, ry, x, y);
    if (!touchHeld) {
        touchHeld = true;
        tapX = x;
        tapY = y;
        touchRepeat = onTouch(x, y) == Tap::Repeat;
        nextRepeatMs = now + 450;
        dirty = true;
    } else if (touchRepeat && static_cast<std::int32_t>(now - nextRepeatMs) >= 0) {
        nextRepeatMs = now + 110;
        onTouch(tapX, tapY);
        dirty = true;
    }
}

void onRotate(int steps) {
    app::Settings& config = app::settings();
    switch (currentPage) {
        case Page::Menu:
            homeIndex = wrap(homeIndex + steps, kHomeCount);
            break;

        case Page::Resistor:
            if (resistorField == 6) {
                app::setOutput(steps > 0);
            } else if (!app::state().locked) {
                app::adjustDigit(static_cast<std::uint8_t>(5 - resistorField), steps);
            }
            break;

        case Page::Ntc:
            if (ntcField == 3) {
                if (steps > 0 && !app::ntcActive()) {
                    app::setNtcTemperature(ntcEditTemp);
                }
                app::setOutput(steps > 0);
            } else if (ntcField == 0) {
                stepNtcType(steps);
            } else {
                stepNtc(steps * (ntcField == 1 ? 1.0 : 0.1));
            }
            break;

        case Page::Bluetooth:
            if (bleField == 0) {
                setBleBridgeMode(!comm::bleBridge());
            } else {
                setBleOn(steps > 0);
            }
            break;

        case Page::Knob:
            if (knobArmed) {
                comm::knobRotate(static_cast<comm::KnobMode>(config.knobMode), steps);
            } else {
                config.knobMode = static_cast<std::uint8_t>(
                    wrap(config.knobMode + steps, static_cast<int>(comm::KnobMode::Count)));
            }
            break;

        case Page::Serial: {
            int index = 0;
            for (int i = 0; i < kBaudCount; ++i) {
                if (kBaudRates[i] == config.bridgeBaud) {
                    index = i;
                }
            }
            config.bridgeBaud = kBaudRates[wrap(index + steps, kBaudCount)];
            comm::setBridgeBaud(config.bridgeBaud);
            break;
        }

        case Page::TempLog: {
            int index = 0;
            for (int i = 0; i < kLogIntervalCount; ++i) {
                if (kLogIntervals[i] == config.logIntervalS) {
                    index = i;
                }
            }
            config.logIntervalS = kLogIntervals[wrap(index + steps, kLogIntervalCount)];
            break;
        }

        case Page::RelayTest:
            if (relayField == 4) {
                if (steps > 0 && !app::relayCycleRunning()) {
                    app::startRelayCycle(relayIndex, relayOnMs, relayOffMs, relayCount);
                } else if (steps < 0) {
                    app::stopRelayCycle();
                }
            } else {
                adjustRelayRow(relayField, steps);
            }
            break;

        case Page::Messages:
            scrollMessages(steps);
            break;

        case Page::About:
            if (settingsField == 0) {
                setBacklightSteps(steps);
            } else if (settingsField == 1) {
                flipScreen();
            } else if (settingsField == 2) {
                toggleLanguage();
            } else if (steps > 0) {
                startTouchCalibration();
            }
            break;

        default:
            break;
    }
}

void onShortPress() {
    app::Settings& config = app::settings();
    switch (currentPage) {
        case Page::Menu:
            setPage(kHome[homeIndex].page);
            break;
        case Page::Resistor:
            resistorField = wrap(resistorField + 1, 7);
            break;
        case Page::Ntc:
            ntcField = wrap(ntcField + 1, 4);
            break;
        case Page::Bluetooth:
            bleField = wrap(bleField + 1, 2);
            break;
        case Page::Knob:
            if (knobArmed) {
                comm::knobClick(static_cast<comm::KnobMode>(config.knobMode));
            } else {
                knobArmed = true;
            }
            break;
        case Page::Serial:
            comm::setBridgePaused(!comm::bridgePaused());
            break;
        case Page::TempLog:
            app::clearTempLog();
            break;
        case Page::RelayTest:
            relayField = wrap(relayField + 1, 5);
            break;
        case Page::About:
            settingsField = wrap(settingsField + 1, 4);
            break;
        case Page::Messages:
            msgScroll = 0;      // back to the newest
            break;
        case Page::TouchCal:
            config.touchSkipped = true;
            app::saveSettings();
            requestedPage = returnPage;
            pageChangePending = true;
            break;
        default:
            break;
    }
}

