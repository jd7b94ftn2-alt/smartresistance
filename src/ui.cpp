void renderShare() {
    if (shareView != ShareView::List && share::indexOf(shareId) < 0) {
        shareView = ShareView::List;       // deleted (FILEDEL) while shown
    }
    // Guard: a decoder / layout that never returns resets the board (task watchdog, 5 s) instead of
    // freezing it; the breadcrumb survives that reset and MEM? reports it.
    const bool guarded = esp_task_wdt_add(nullptr) == ESP_OK;
    diagCrumb = 0xA0000000U | (static_cast<std::uint32_t>(shareView) << 16) | shareId;
    switch (shareView) {
        case ShareView::Image: renderShareImage(); break;
        case ShareView::Text: renderShareText(); break;
        default: renderShareList(); break;
    }
    diagCrumb = 0;
    if (guarded) {
        esp_task_wdt_delete(nullptr);
    }
}

void shareBackToList() {
    shareView = ShareView::List;
    clearContent();
    dirty = true;
}

// Previous / next file in the list, from a viewer.
void shareNeighbour(int step) {
    share::Item it;
    if (share::item(shareSel + step, it)) {
        openShared(it.id);
        clearContent();
    }
}

void shareStep(int steps) {
    if (shareView == ShareView::Text) {
        loadReaderSize();
        textTop += steps * readerLines();
        return;
    }
    if (shareView == ShareView::Image) {
        zoomBy(steps > 0 ? 1 : -1);            // knob = zoom
        return;
    }
    const int n = share::count();
    if (n > 0) {
        shareSel = std::max(0, std::min(n - 1, shareSel + steps));
    }
}

Tap shareTouch(int x, int y) {
    if (shareView == ShareView::Image) {
        const std::uint32_t now = millis();
        if (static_cast<std::int32_t>(now - toolbarUntil) < 0 && y >= kToolbarY) {
            switch (std::min(5, x / 53)) {
                case 0: shareBackToList(); return Tap::Done;
                case 1: shareNeighbour(-1); return Tap::Done;
                case 2: zoomBy(-1); break;
                case 3: zoomLevel = 0; break;
                case 4: zoomBy(1); break;
                default: shareNeighbour(1); return Tap::Done;
            }
            toolbarUntil = now + 4000;
            return Tap::Done;
        }
        if (zoomLevel > 0 && viewZw > 0 && viewZh > 0) {   // look at the tapped spot
            viewCx = static_cast<float>(x - viewOx + viewVx) / viewZw;
            viewCy = static_cast<float>(y - viewOy + viewVy) / viewZh;
        }
        toolbarUntil = now + 4000;
        return Tap::Done;
    }
    if (y < kBar) {
        return Tap::None;
    }
    if (shareView == ShareView::Text) {
        loadReaderSize();
        if (kTextSmaller.contains(x, y)) {
            setReaderSize(readerSize - 1);
            return Tap::Done;
        }
        if (kTextBigger.contains(x, y)) {
            setReaderSize(readerSize + 1);
            return Tap::Done;
        }
        if (y < 211) {
            textTop += (y < (kBar + 211) / 2 ? -1 : 1) * readerLines();
            return Tap::Repeat;
        }
        return Tap::None;
    }
    if (kShareDelete.contains(x, y)) {
        share::Item it;
        if (shareDelConfirm && share::item(shareSel, it)) {
            share::remove(it.id);
            shareDelConfirm = false;
        } else if (share::count() > 0) {
            shareDelConfirm = true;
            shareDelUntil = millis() + 3000;
        }
        return Tap::Done;
    }
    for (int row = 0; row < kShareRows; ++row) {
        const int top = kShareRowY + row * kShareRowH;
        share::Item it;
        if (y >= top && y < top + kShareRowH && share::item(shareTop + row, it)) {
            openShared(it.id);
            clearContent();
            return Tap::Done;
        }
    }
    return Tap::None;
}

void sharePress() {
    if (shareView != ShareView::List) {
        shareBackToList();
        return;
    }
    share::Item it;
    if (share::item(shareSel, it)) {
        openShared(it.id);
        clearContent();
    }
}

// ------------------------------------------------------------ page switching / dispatch
void clearContent() {
    useFont(Font::Builtin);
    gfx->fillRect(0, 0, kWidth, kHeight, kBg);   // not fillScreen: a sprite keeps the 240x320 default size there
    resetSlots();
    if (currentPage == Page::TouchCal) {
        return;
    }
    gfx->fillRect(0, 0, kWidth, kBar, kBarColor);
    gfx->drawFastHLine(0, kBar, kWidth, kBorder);
    switch (currentPage) {
        case Page::Resistor: staticResistor(); break;
        case Page::Ntc: staticNtc(); break;
        default: break;
    }
}

void enterPage(Page page) {
    // Leaving a page: stop what only makes sense while it is shown.
    if (currentPage == Page::RelayTest && page != Page::RelayTest) {
        app::leaveRawMode();
    }
    if (currentPage == Page::Serial && page != Page::Serial) {
        comm::setBridgePaused(false);
    }
    if (currentPage != Page::Menu && page == Page::Menu) {
        app::saveSettings();
    }
    if (currentPage == Page::Game && page != Page::Game) {
        game::pause(millis());
    }
    if (page == Page::Game) {
        game::begin();
    }
    if (currentPage == Page::Share && page != Page::Share) {
        freeZoomCache();                 // up to 2.4 MB of PSRAM for a zoomed picture
    }
    if (page == Page::Share) {
        shareDelConfirm = false;
        if (shareOpenPending >= 0) {
            openShared(static_cast<std::uint16_t>(shareOpenPending));   // a file that just arrived
            shareOpenPending = -1;
        } else {
            shareView = ShareView::List;
        }
    }

    currentPage = page;
    bannerShown = false;
    knobArmed = false;
    bridgeDrawnRev = 0xFFFFFFFF;
    tempDrawnCount = -1;
    touchHeld = true;          // ignore the finger that is still on the glass after a page change
    touchRepeat = false;
    if (page == Page::Ntc) {
        ntcEditTemp = app::ntcTemperature();
    }
    if (page == Page::Messages) {
        msgScroll = 0;
        msg::markAllRead();
    }
    bankConfirm = false;
    if (page == Page::Menu) {
        for (int i = 0; i < kHomeCount; ++i) {
            if (kHome[i].page == returnPage) {
                homeIndex = i;
            }
        }
    }
    clearContent();
    if (page == Page::TouchCal) {
        restartCalibration();
    }
    dirty = true;
}

void renderPage() {
    if (currentPage == Page::TouchCal) {
        return;
    }
    if (!(currentPage == Page::Share && shareView == ShareView::Image && !bannerShown)) {
        drawStatusBar();     // a shared picture uses the whole screen
    }
    if (bannerShown) {
        return;              // page frozen under the banner
    }
    switch (currentPage) {
        case Page::Menu: renderHome(); break;
        case Page::Resistor: renderResistor(); break;
        case Page::Ntc: renderNtc(); break;
        case Page::Bluetooth: renderBluetooth(); break;
        case Page::Knob: renderKnob(); break;
        case Page::Serial: renderSerial(); break;
        case Page::TempLog: renderTempLog(); break;
        case Page::Info: renderInfo(); break;
        case Page::RelayTest: renderRelayTest(); break;
        case Page::About: renderAbout(); break;
        case Page::Messages: renderMessages(); break;
        case Page::Desk: renderDesk(); break;
        case Page::Macro: renderMacro(); break;
        case Page::Pomodoro: renderPomodoro(); break;
        case Page::NtcPick: renderNtcPick(); break;
        case Page::PowerBank: renderPowerBank(); break;
        case Page::Remote: renderRemote(); break;
        case Page::Game: renderGame(); break;
        case Page::System: renderSystem(); break;
        case Page::Share: renderShare(); break;
        default: break;
    }
}

Tap onTouch(int x, int y) {
    if (bannerShown) {
        if (y >= kBannerY && y < kBannerY + kBannerH) {
            bannerShown = false;
            returnPage = currentPage;
            setPage(bannerIsTimer ? Page::Pomodoro : Page::Messages);
        } else {
            hideBanner();
        }
        return Tap::Done;
    }
    if (currentPage == Page::Share && shareView == ShareView::Image) {
        return shareTouch(x, y);         // full-screen picture: any tap goes back to the list
    }
    if (currentPage != Page::Menu && y < kBar && x < 80) {
        goHome();
        return Tap::Done;
    }
    // "新消息 N" in the status bar opens the message list.
    if (y < kBar && x >= 166 && x < 266 && msg::count() > 0 && currentPage != Page::Messages) {
        returnPage = currentPage;
        setPage(Page::Messages);
        return Tap::Done;
    }
    app::Settings& config = app::settings();
    switch (currentPage) {
        case Page::Info:
            if (y >= kInfoCardY && msg::count() > 0) {
                setPage(Page::Messages);
                return Tap::Done;
            }
            break;

        case Page::Messages:
            if (y >= kBar) {
                scrollMessages(y < kHeight / 2 ? -1 : 1);
                return Tap::Repeat;
            }
            break;

        case Page::Desk:
            if (kDeskPrev.contains(x, y)) {
                deskMedia(comm::Action::PrevTrack, apple::Command::Previous);
                return Tap::Done;
            }
            if (kDeskPlay.contains(x, y)) {
                deskMedia(comm::Action::PlayPause, apple::Command::TogglePlayPause);
                return Tap::Done;
            }
            if (kDeskNext.contains(x, y)) {
                deskMedia(comm::Action::NextTrack, apple::Command::Next);
                return Tap::Done;
            }
            break;

        case Page::Macro:
            for (int i = 0; i < desk::kMacroCount; ++i) {
                if (macroButton(i).contains(x, y)) {
                    fireMacro(i);
                    return Tap::Done;
                }
            }
            break;

        case Page::Pomodoro:
            return timerTouch(x, y);

        case Page::NtcPick:
            return ntcPickTouch(x, y);

        case Page::PowerBank:
            if (kBankMode.contains(x, y)) {
                bankModePress();
                return Tap::Done;
            }
            break;

        case Page::Remote:
            for (int i = 0; i < 9; ++i) {
                if (kRemoteButton[i].contains(x, y)) {
                    remotePress(i);
                    return Tap::Done;
                }
            }
            break;

        case Page::Game:
            return gameTouch(x, y);

        case Page::System:
            if (kSysClean.contains(x, y)) {
                sysClean();
                return Tap::Done;
            }
            break;

        case Page::Share:
            return shareTouch(x, y);

        case Page::Menu:
            for (int i = 0; i < kHomeCount; ++i) {
                if (homeTile(i).contains(x, y)) {
                    homeIndex = i;
                    setPage(kHome[i].page);
                    return Tap::Done;
                }
            }
            break;

        case Page::Resistor:
            for (int i = 0; i < 6; ++i) {
                const int dx = digitX(i);
                if (x >= dx - 4 && x < dx + 36 && y >= 28 && y < 108) {
                    resistorField = i;
                    if (!app::state().locked) {
                        app::adjustDigit(static_cast<std::uint8_t>(5 - i), y < 67 ? 1 : -1);
                    }
                    return Tap::Repeat;
                }
            }
            if (kOutputButton.contains(x, y)) {
                resistorField = 6;
                app::setOutput(!app::state().outputEnabled);
                return Tap::Done;
            }
            break;

        case Page::Ntc:
            if (kNtcType.contains(x, y)) {
                ntcField = 0;
                openNtcPicker();
                return Tap::Done;
            }
            for (int i = 0; i < 4; ++i) {
                if (kNtcStep[i].contains(x, y)) {
                    ntcField = (i == 0 || i == 3) ? 1 : 2;
                    stepNtc(kNtcStepValue[i]);
                    return Tap::Repeat;
                }
            }
            if (kNtcOutput.contains(x, y)) {
                ntcField = 3;
                const bool on = !app::state().outputEnabled;
                if (on && !app::ntcActive()) {
                    app::setNtcTemperature(ntcEditTemp);
                }
                app::setOutput(on);
                return Tap::Done;
            }
            break;

        case Page::Bluetooth:
            for (int i = 0; i < 2; ++i) {
                if (kBleMode[i].contains(x, y)) {
                    bleField = 0;
                    setBleBridgeMode(i == 1);
                    return Tap::Done;
                }
            }
            if (kBleToggle.contains(x, y)) {
                bleField = 1;
                setBleOn(!comm::bleEnabled());
                return Tap::Done;
            }
            break;

        case Page::Knob:
            for (int i = 0; i < 4; ++i) {
                if (kKnobMode[i].contains(x, y)) {
                    config.knobMode = static_cast<std::uint8_t>(i);
                    knobArmed = false;
                    return Tap::Done;
                }
            }
            if (kKnobStart.contains(x, y)) {
                knobArmed = !knobArmed;
                return Tap::Done;
            }
            break;

        case Page::Serial:
            if (kSerialBaud.contains(x, y)) {
                int index = 0;
                for (int i = 0; i < kBaudCount; ++i) {
                    if (kBaudRates[i] == config.bridgeBaud) {
                        index = i;
                    }
                }
                config.bridgeBaud = kBaudRates[wrap(index + 1, kBaudCount)];
                comm::setBridgeBaud(config.bridgeBaud);
                return Tap::Done;
            }
            if (kSerialPause.contains(x, y)) {
                comm::setBridgePaused(!comm::bridgePaused());
                return Tap::Done;
            }
            if (kSerialClear.contains(x, y)) {
                comm::clearBridgeLog();
                return Tap::Done;
            }
            break;

        case Page::TempLog:
            if (kLogInterval.contains(x, y)) {
                int index = 0;
                for (int i = 0; i < kLogIntervalCount; ++i) {
                    if (kLogIntervals[i] == config.logIntervalS) {
                        index = i;
                    }
                }
                config.logIntervalS = kLogIntervals[wrap(index + 1, kLogIntervalCount)];
                return Tap::Done;
            }
            if (kLogClear.contains(x, y)) {
                app::clearTempLog();
                return Tap::Done;
            }
            break;

        case Page::RelayTest:
            for (int row = 0; row < 4; ++row) {
                if (relayMinus(row).contains(x, y) || relayPlus(row).contains(x, y)) {
                    relayField = row;
                    adjustRelayRow(row, relayPlus(row).contains(x, y) ? 1 : -1);
                    return Tap::Repeat;
                }
            }
            if (kRelayStart.contains(x, y)) {
                relayField = 4;
                toggleRelayCycle();
                return Tap::Done;
            }
            break;

        case Page::About:
            if (kLightMinus.contains(x, y) || kLightPlus.contains(x, y)) {
                settingsField = 0;
                setBacklightSteps(kLightPlus.contains(x, y) ? 1 : -1);
                return Tap::Repeat;
            }
            if (kFlipButton.contains(x, y)) {
                settingsField = 1;
                flipScreen();
                return Tap::Done;
            }
            if (kLangButton.contains(x, y)) {
                settingsField = 2;
                toggleLanguage();
                return Tap::Done;
            }
            if (kCalButton.contains(x, y)) {
                settingsField = 3;
                startTouchCalibration();
                return Tap::Done;
            }
            if (kTouchOffButton.contains(x, y) && config.touchValid) {
                config.touchValid = false;
                config.touchSkipped = true;
                app::saveSettings();
                return Tap::Done;
            }
            break;

        default:
            break;
    }
    return Tap::None;
}

void pollTouch(std::uint32_t now) {
    if (now - lastTouchPollMs < kTouchPollMs) {
        return;
    }
    lastTouchPollMs = now;
    if (!app::settings().touchValid) {
        return;
    }
    std::uint16_t rx = 0;
    std::uint16_t ry = 0;
    std::uint16_t rz = 0;
    if (!readTouchRaw(rx, ry, rz)) {
        touchDownCount = 0;
        touchHeld = false;
        return;
    }
    if (++touchDownCount < 2) {
        return;   // two consecutive samples before a tap counts
    }
    int x = 0;
    int y = 0;
    mapTouch(rx, ry, x, y);
    if (!touchHeld) {
        touchHeld = true;
        tapX = x;
        tapY = y;
        touchRepeat = onTouch(x, y) == Tap::Repeat;
        nextRepeatMs = now + 450;
        dirty = true;
    } else if (touchRepeat && static_cast<std::int32_t>(now - nextRepeatMs) >= 0) {
        nextRepeatMs = now + 110;
        onTouch(tapX, tapY);
        dirty = true;
    }
}

void onRotate(int steps) {
    app::Settings& config = app::settings();
    switch (currentPage) {
        case Page::Menu:
            homeIndex = wrap(homeIndex + steps, kHomeCount);
            break;

        case Page::Resistor:
            if (resistorField == 6) {
                app::setOutput(steps > 0);
            } else if (!app::state().locked) {
                app::adjustDigit(static_cast<std::uint8_t>(5 - resistorField), steps);
            }
            break;

        case Page::Ntc:
            if (ntcField == 3) {
                if (steps > 0 && !app::ntcActive()) {
                    app::setNtcTemperature(ntcEditTemp);
                }
                app::setOutput(steps > 0);
            } else if (ntcField == 0) {
                openNtcPicker();          // two-column R25 / B picker
            } else {
                stepNtc(steps * (ntcField == 1 ? 1.0 : 0.1));
            }
            break;

        case Page::NtcPick:
            ntcPickRotate(steps);
            break;

        case Page::Bluetooth:
            if (bleField == 0) {
                setBleBridgeMode(!comm::bleBridge());
            } else {
                setBleOn(steps > 0);
            }
            break;

        case Page::Knob:
            if (knobArmed) {
                comm::knobRotate(static_cast<comm::KnobMode>(config.knobMode), steps);
            } else {
                config.knobMode = static_cast<std::uint8_t>(
                    wrap(config.knobMode + steps, static_cast<int>(comm::KnobMode::Count)));
            }
            break;

        case Page::Serial: {
            int index = 0;
            for (int i = 0; i < kBaudCount; ++i) {
                if (kBaudRates[i] == config.bridgeBaud) {
                    index = i;
                }
            }
            config.bridgeBaud = kBaudRates[wrap(index + steps, kBaudCount)];
            comm::setBridgeBaud(config.bridgeBaud);
            break;
        }

        case Page::TempLog: {
            int index = 0;
            for (int i = 0; i < kLogIntervalCount; ++i) {
                if (kLogIntervals[i] == config.logIntervalS) {
                    index = i;
                }
            }
            config.logIntervalS = kLogIntervals[wrap(index + steps, kLogIntervalCount)];
            break;
        }

        case Page::RelayTest:
            if (relayField == 4) {
                if (steps > 0 && !app::relayCycleRunning()) {
                    app::startRelayCycle(relayIndex, relayOnMs, relayOffMs, relayCount);
                } else if (steps < 0) {
                    app::stopRelayCycle();
                }
            } else {
                adjustRelayRow(relayField, steps);
            }
            break;

        case Page::Messages:
            scrollMessages(steps);
            break;

        case Page::Desk:
            for (int i = 0; i < (steps < 0 ? -steps : steps); ++i) {
                deskMedia(steps > 0 ? comm::Action::VolumeUp : comm::Action::VolumeDown,
                    steps > 0 ? apple::Command::VolumeUp : apple::Command::VolumeDown);
            }
            break;

        case Page::Macro:
            macroField = wrap(macroField + steps, desk::kMacroCount);
            break;

        case Page::Remote:
            for (int i = 0; i < (steps < 0 ? -steps : steps); ++i) {
                comm::sendRemote(steps > 0 ? comm::Remote::VolumeUp : comm::Remote::VolumeDown);
            }
            break;

        case Page::Game:
            for (int i = 0; i < (steps < 0 ? -steps : steps); ++i) {
                game::move(steps > 0 ? 1 : -1, millis());
            }
            break;

        case Page::Share:
            shareStep(steps);
            break;

        case Page::Pomodoro:
            if (timerMode == 0 && !pomoRunning && !pomoPaused) {
                pomoDone = false;
                pomoMinutes = std::max(1, std::min(180, pomoMinutes + steps));
            }
            break;

        case Page::About:
            if (settingsField == 0) {
                setBacklightSteps(steps);
            } else if (settingsField == 1) {
                flipScreen();
            } else if (settingsField == 2) {
                toggleLanguage();
            } else if (steps > 0) {
                startTouchCalibration();
            }
            break;

        default:
            break;
    }
}

void onShortPress() {
    app::Settings& config = app::settings();
    switch (currentPage) {
        case Page::Menu:
            setPage(kHome[homeIndex].page);
            break;
        case Page::Resistor:
            resistorField = wrap(resistorField + 1, 7);
            break;
        case Page::Ntc:
            ntcField = wrap(ntcField + 1, 4);
            break;
        case Page::Bluetooth:
            bleField = wrap(bleField + 1, 2);
            break;
        case Page::Knob:
            if (knobArmed) {
                comm::knobClick(static_cast<comm::KnobMode>(config.knobMode));
            } else {
                knobArmed = true;
            }
            break;
        case Page::Serial:
            comm::setBridgePaused(!comm::bridgePaused());
            break;
        case Page::TempLog:
            app::clearTempLog();
            break;
        case Page::RelayTest:
            relayField = wrap(relayField + 1, 5);
            break;
        case Page::About:
            settingsField = wrap(settingsField + 1, 4);
            break;
        case Page::Messages:
            msgScroll = 0;      // back to the newest
            break;
        case Page::Desk:
            deskMedia(comm::Action::PlayPause, apple::Command::TogglePlayPause);
            break;
        case Page::Macro:
            fireMacro(macroField);
            break;
        case Page::Pomodoro:
            pomoStartPause();
            break;
        case Page::NtcPick:
            ntcPickPress();
            break;
        case Page::PowerBank:
            bankModePress();
            break;
        case Page::Remote:
            remotePress(1);           // play / pause
            break;
        case Page::Game:
            gamePress();
            break;
        case Page::System:
            sysClean();
            break;
        case Page::Share:
            sharePress();
            break;
        case Page::TouchCal:
            config.touchSkipped = true;
            app::saveSettings();
            requestedPage = returnPage;
            pageChangePending = true;
            break;
        default:
            break;
    }
}

