// ------------------------------------------------------------ fonts
// Two anti-aliased fonts (16 / 24 px, generated by tools/make_fonts.py with only the glyphs this
// file uses) plus the built-in fonts: 1 = 6x8, 7 = 7-segment digits. TFT_eSPI holds one smooth
// font at a time, so useFont() swaps on demand; parsing the metrics takes well under 1 ms.
enum class Font : std::uint8_t { Builtin, Small, Large };
Font loadedFont = Font::Builtin;

void useFont(Font font) {
    if (font == loadedFont) {
        return;
    }
    if (loadedFont != Font::Builtin) {
        gfx->unloadFont();
    }
    if (font == Font::Small) {
        gfx->loadFont(kFontZh16);
    } else if (font == Font::Large) {
        gfx->loadFont(kFontZh24);
    }
    loadedFont = font;
}

// fillBox = false: no line-height background box (smooth fonts still blend with bg). Use it for text on a
// surface that was just painted (buttons), where the 20 / 27 px box could stick out of the shape.
void text(const String& value, int x, int y, Font font, std::uint16_t fg, std::uint16_t bg, int padding,
    std::uint8_t datum, int builtinFont, bool fillBox = true) {
    useFont(font);
    gfx->setTextDatum(datum);
    gfx->setTextColor(fg, bg, fillBox);
    gfx->setTextPadding(padding);
    if (font == Font::Builtin) {
        gfx->drawString(value, x, y, builtinFont);
    } else {
        gfx->drawString(value, x, y);
    }
}

// ------------------------------------------------------------ widgets with a redraw cache
// Every widget has a slot id; it is repainted only when its text or style changed, which keeps
// the 150 ms refresh flicker-free. Slots are cleared whenever a page is (re)entered.
constexpr int kSlots = 64;
String slotText[kSlots];
std::uint32_t slotKey[kSlots];

void resetSlots() {
    for (int i = 0; i < kSlots; ++i) {
        slotText[i] = "\x01";
        slotKey[i] = 0xFFFFFFFF;
    }
}

bool changed(int id, const String& value, std::uint32_t key) {
    if (slotKey[id] == key && slotText[id] == value) {
        return false;
    }
    slotText[id] = value;
    slotKey[id] = key;
    return true;
}

